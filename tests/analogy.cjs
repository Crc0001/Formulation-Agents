const assert=require('node:assert/strict');
const {fitLine,transferDelta,fraction,runVariant,sourceMetrics}=require('../apps/web/src/analogy.ts');
const f=fitLine([[0,.19],[5,.21],[20,.24]]);
assert.ok(Math.abs(f.slope-.002384615384615385)<1e-12);
assert.ok(Math.abs(f.intercept-.19346153846153846)<1e-12);
assert.ok(Math.abs(f.residuals.reduce((a,b)=>a+b,0))<1e-12);
assert.equal(fitLine([[0,1],[1,3],[2,5]]).rmse,0);
assert.throws(()=>fitLine([[0,1],[0,2],[0,3]]));
assert.throws(()=>fitLine([[0,1],[1,NaN],[2,3]]));
assert.equal(transferDelta(f.slope,10,10,1),0);
assert.equal(transferDelta(f.slope,10,20,0),0);
assert.equal(transferDelta(f.slope,10,20,-1),-transferDelta(f.slope,10,20,1));
assert.ok(Math.abs(transferDelta(f.slope,10,100*29/140,1)-2.554945054945055)<1e-10);
assert.equal(fraction([{id:'a',amount_mg:10},{id:'b',amount_mg:30}],'a'),25);
assert.throws(()=>fraction([{id:'a',amount_mg:NaN}],'a'));
assert.equal(runVariant({message:'prefix\n变化方案：{"id":"a"}\n问题：x'}),'a');
assert.equal(runVariant({message:'unknown'}),null);
const source={id:'s',source_url:'url'},m={source_id:'s',quantity:'scalar',unit:'%',conditions:'same',points:[{label:'a',value:1},{label:'b',value:2}]};
const e=x=>({id:x.title,fields:{source_metric_json:JSON.stringify(x)}});
assert.equal(sourceMetrics([source,e({...m,title:'first'}),e({...m,title:'renamed'})]).length,1);
assert.equal(sourceMetrics([source,e(m),e({...m,conditions:'other'})]).length,2);
console.log('Analogy checks passed: OLS, residuals, invalid inputs, zero/reverse transfer, percent units, frozen version matching and condition-aware deduplication');
